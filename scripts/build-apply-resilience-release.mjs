import assert from 'node:assert/strict';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { files } from './funnel-support.mjs';
const [source,output,build]=process.argv.slice(2);
assert(source && output && build && path.resolve(source)!==path.resolve(output));
const html=await readFile(path.join(source,'apply/index.html'),'utf8');
const built=await readFile(path.join(build,'index.html'),'utf8');
const asset=built.match(/src="\/apply\/([^" ]+\.js)"/)[1];
const css=built.match(/href="\/apply\/([^" ]+\.css)"/)[1];
const oldCss=html.match(/href="\/apply\/([^" ]+\.css)"/)[1];
assert((await readFile(path.join(source,'apply',oldCss))).equals(await readFile(path.join(build,css))));
const js=await readFile(path.join(build,asset));
assert(js.toString().includes('https://formspree.io/f/mpwdnokz'));
const next=html.replace(/src="\/apply\/assets\/index-[\w-]+\.js"/,`src="/apply/${asset}"`);
assert.notEqual(next,html);
await mkdir(output);await cp(source,output,{recursive:true});
await writeFile(path.join(output,'apply',asset),js);
await writeFile(path.join(output,'apply/index.html'),next);
for(const file of await files(source)) if(file!=='apply/index.html') assert((await readFile(path.join(source,file))).equals(await readFile(path.join(output,file))),`Unexpected change ${file}`);
console.log(JSON.stringify({output,asset,css:'unchanged',allOtherFiles:'unchanged'}));
